package organizaai.modelo;

/**
 * Representa as categorias disponíveis para classificar as atividades da agenda.
 * Facilita a organização da rotina do usuário (ex: separar estudos do trabalho).
 */
public enum Categoria {
    //Atividades pessoais, como lazer
    PESSOAL,
    //Atividades da vida acadêmica
    FACULDADE,
    //Atividades relacionados ao trabalho
    TRABALHO,
    //Atividades que estão relacionados aos cuidados com a saúde (ex.: dentista marcado)
    SAUDE
}